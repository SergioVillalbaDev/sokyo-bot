const traducirError = (texto) => (typeof texto === 'string' && EN[texto]) || texto;

// Middleware: con el panel en inglés, el `error` de las respuestas JSON sale traducido.
function middlewareErrores(req, res, next) {
    const lang = String(req.get('x-sokyo-lang') || '').slice(0, 2).toLowerCase();
    if (lang !== 'en') return next();
    const json = res.json.bind(res);
    res.json = (cuerpo) => {
        if (cuerpo && typeof cuerpo === 'object' && !Array.isArray(cuerpo) && typeof cuerpo.error === 'string' && EN[cuerpo.error]) {
            cuerpo = { ...cuerpo, error: EN[cuerpo.error] };
        }
        return json(cuerpo);
    };
    next();
}

